import ExcelJS from 'exceljs';
const input='server/templates/formato-herramienta-danada.xlsx';
const output='/tmp/reporte-prueba-media.xlsx';
const base=new ExcelJS.Workbook();
await base.xlsx.readFile(input);
const baseMedia=base.media.length;
const wb=new ExcelJS.Workbook();
await wb.xlsx.readFile(input);
const ws=wb.worksheets[0];
const logo=wb.addImage({filename:'server/templates/logo-marcobre.png',extension:'png'});
ws.addImage(logo,{tl:{col:7,row:0},ext:{width:245,height:48}});
const photo=wb.addImage({filename:'server/templates/logo-marcobre.png',extension:'png'});
ws.addImage(photo,{tl:{col:1,row:20},ext:{width:190,height:112}});
ws.getCell('B26').value='Evidencia 1 – Estado de la herramienta al momento de la baja.';
await wb.xlsx.writeFile(output);
const check=new ExcelJS.Workbook();
await check.xlsx.readFile(output);
if (check.media.length < baseMedia + 2) throw new Error(`No se añadieron logo y foto: base=${baseMedia}, final=${check.media.length}`);
if (check.worksheets[0].getCell('B26').value !== 'Evidencia 1 – Estado de la herramienta al momento de la baja.') throw new Error('La leyenda no quedó guardada');
console.log(`OK: ${output}; medios base=${baseMedia}, final=${check.media.length}; leyenda=presente`);
